import assert from 'node:assert/strict';
import worker from './index.js';
const endpoint='https://example.workers.dev/mcp';
const req=(method,body,auth='secret')=>new Request(endpoint,{method,headers:{authorization:`Bearer ${auth}`,'content-type':'application/json'},body:body?JSON.stringify(body):undefined});
const env={MCP_ACCESS_TOKEN:'secret',MONEYLOVER_EMAIL:'fake@example.invalid',MONEYLOVER_PASSWORD:'fake'};
const json=async r=>({status:r.status,data:await r.json()});
assert.equal((await worker.fetch(req('POST',{jsonrpc:'2.0',id:1,method:'tools/list'}),{})).status,503);
assert.equal((await worker.fetch(req('POST',{jsonrpc:'2.0',id:1,method:'tools/list'},'incorrect'),env)).status,401);
const tools=await json(await worker.fetch(req('POST',{jsonrpc:'2.0',id:1,method:'tools/list'}),env));
assert.equal(tools.status,200);
assert.deepEqual(tools.data.result.tools.map(x=>x.name),['get_wallets','get_categories','get_transactions']);
const bad=await json(await worker.fetch(req('POST',{jsonrpc:'2.0',id:2,method:'tools/call',params:{name:'add_transaction'}}),env));
assert.equal(bad.status,400);
const dated=await json(await worker.fetch(req('POST',{jsonrpc:'2.0',id:3,method:'tools/call',params:{name:'get_transactions',arguments:{walletId:'abc',startDate:'2026-01-01',endDate:'2026-08-01'}}}),env));
assert.equal(dated.data.result.isError,true);
const incompleteAccessEnv={...env,ACCESS_TEAM_DOMAIN:'https://example.cloudflareaccess.com'};
const incomplete=await json(await worker.fetch(req('POST',{jsonrpc:'2.0',id:6,method:'tools/list'}),incompleteAccessEnv));
assert.equal(incomplete.status,503);
assert.equal(incomplete.data.error,'Access configuration incomplete');
const accessEnv={...env,ACCESS_TEAM_DOMAIN:'https://example.cloudflareaccess.com',ACCESS_AUD:'example-audience'};
const listReq=req('POST',{jsonrpc:'2.0',id:4,method:'tools/list'});
assert.equal((await worker.fetch(listReq,accessEnv)).status,401);
assert.equal((await worker.fetch(req('POST',{jsonrpc:'2.0',id:5,method:'tools/list'}),accessEnv,{})).status,401);
const spoofedHeader=new Request(endpoint,{method:'POST',headers:{authorization:'Bearer secret','Cf-Access-Jwt-Assertion':'forged','content-type':'application/json'},body:JSON.stringify({jsonrpc:'2.0',id:7,method:'tools/list'})});
assert.equal((await worker.fetch(spoofedHeader,accessEnv)).status,401);
const wrongAudContext={access:{aud:'another-application'}};
assert.equal((await worker.fetch(req('POST',{jsonrpc:'2.0',id:8,method:'tools/list'}),accessEnv,wrongAudContext)).status,401);
const trustedContext={access:{aud:'example-audience'}};
const authenticated=await json(await worker.fetch(req('POST',{jsonrpc:'2.0',id:9,method:'tools/list'}),accessEnv,trustedContext));
assert.equal(authenticated.status,200);
assert.deepEqual(authenticated.data.result.tools.map(x=>x.name),['get_wallets','get_categories','get_transactions']);
const authenticatedGet=await worker.fetch(new Request(endpoint,{method:'GET'}),accessEnv,trustedContext);
assert.equal(authenticatedGet.status,405);
console.log('PASS: fail closed, unauthorized denied, tools read-only, writes denied, date bounds enforced, trusted Access context and audience required');
